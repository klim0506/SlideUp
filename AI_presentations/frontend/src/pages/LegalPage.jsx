function currentDoc() {
  const slug = window.location.pathname.match(/^\/legal\/([^/]+)\/?$/)?.[1] || "offer";
  return docs[slug] ? { slug, doc: docs[slug] } : { slug: "offer", doc: docs.offer };
}

export default function LegalPage() {
  const { slug, doc } = currentDoc();
  const [user, setUser] = useState(null);
  const [authOpen, setAuthOpen] = useState(false);

  useEffect(() => {
    getMe().then(setUser).catch(() => setUser(null));
  }, []);

  const hasPlaceholders = [LEGAL.entityName, LEGAL.inn, LEGAL.ogrn, LEGAL.legalAddress, LEGAL.phone].some((value) =>
    String(value).startsWith("Укажите"),
  );

  function handleAuthSuccess() {
    getMe().then(setUser).catch(() => setUser(null));
  }

  return (
    <div className="su-page">
      <SiteHeader user={user} onLogin={() => setAuthOpen(true)} />
      <main className="su-container legal-page">
        <div className="legal-layout">
          <aside className="legal-sidebar" aria-label="Юридические документы">
            {DOCUMENT_LINKS.map((link) => {
              const active = link.href.endsWith(slug);
              return (
                <a
                  key={link.href}
                  href={link.href}
                  onClick={(event) => {
                    event.preventDefault();
                    navigate(link.href);
                    window.scrollTo({ top: 0, behavior: "smooth" });
                  }}
                  style={active ? { background: "var(--surface-2)", color: "var(--ink)", fontWeight: 700 } : undefined}
                >
                  {link.label}
                </a>
              );
            })}
          </aside>

          <article className="legal-article">
            <h1>{doc.title}</h1>
            <div className="legal-meta">Редакция от {LEGAL.updatedAt}</div>
            {hasPlaceholders ? (
              <div style={{ padding: "12px 14px", borderRadius: "var(--r-md)", background: "#fff7ed", border: "1px solid #fed7aa", color: "#9a3412", fontSize: 13, marginBottom: 24 }}>
                Перед публикацией заполните реальные реквизиты владельца сервиса в переменных VITE_LEGAL_*.
              </div>
            ) : null}
            <p>{doc.lead}</p>

            {doc.requisites ? <Requisites /> : null}

            {doc.sections.map((section) => (
              <section key={section.title}>
                <h2>{section.title}</h2>
                {section.body.map((paragraph) => (
                  <p key={paragraph}>{paragraph}</p>
                ))}
              </section>
            ))}
          </article>
        </div>
      </main>
      <SiteFooter />
      <AuthModal open={authOpen} onClose={() => setAuthOpen(false)} onSuccess={handleAuthSuccess} />
    </div>
  );
}

function Requisites() {
  const rows = [
    ["Наименование", LEGAL.entityName],
    ["ИНН", LEGAL.inn],
    ["ОГРН/ОГРНИП", LEGAL.ogrn],
    ["КПП", LEGAL.kpp],
    ["Юридический адрес", LEGAL.legalAddress],
    ["Почтовый адрес", LEGAL.postalAddress],
    ["Email поддержки", LEGAL.supportEmail],
    ["Email по ПДн", LEGAL.legalEmail],
    ["Телефон", LEGAL.phone],
    ["Режим работы", LEGAL.workTime],
    ["Сайт", LEGAL.serviceUrl],
  ];

  return (
    <dl className="legal-requisites" style={{ marginTop: 28 }}>
      {rows.map(([label, value]) => (
        <div key={label}>
          <dt>{label}</dt>
          <dd style={{ margin: 0 }}>{value}</dd>
        </div>
      ))}
    </dl>
  );
}
