"""Промпты и контракт генерации слайд-дек (русская версия, компактная).

Транспорт ответа — JSON-обёртка {title, slides:[{html, metadata}]}; содержимое
слайда — HTML-фрагмент. Технические токены (теги, классы, ключи JSON, ключи
стилей и дизайнов) — литералы и не переводятся.

Валидация и нормализация ответа модели — на сервере (apps.generation.postprocessing);
здесь модели передаётся лишь компактная форма ответа, без формальной JSON Schema.
"""


# --- Форма ответа -------------------------------------------------------------

RESPONSE_SHAPE = (
    "ФОРМА ОТВЕТА — один JSON-объект такой формы:\n"
    "{\n"
    '  "title": "заголовок презентации",\n'
    '  "slides": [\n'
    "    {\n"
    '      "html": "<section class=\\"slide …\\" data-format=\\"html_v1\\">…</section>",\n'
    '      "metadata": {\n'
    '        "layout": "title|content|grid|quote|stats|cta|timeline|comparison|hero|…",\n'
    '        "title": "заголовок слайда",\n'
    '        "icon": "эмодзи, опц.",\n'
    '        "image_ref": "primary, либо поле отсутствует",\n'
    '        "chart": {"type":"bar|column|line|area|pie|doughnut|radar","title":"…",'
    '"data":[{"label":"…","value":0}]}\n'
    "      }\n"
    "    }\n"
    "  ]\n"
    "}\n"
    "Обязателен только html у каждого слайда; metadata и её поля опциональны."
    " chart добавляйте лишь для числовых данных (2-16 точек)."
)


# --- Контракт HTML (краткий) --------------------------------------------------

HTML_CONTRACT = (
    "ФОРМАТ И ОГРАНИЧЕНИЯ:\n"
    "- Каждый слайд — один корневой <section class=\"slide slide-{layout}\""
    " data-layout=\"{layout}\" data-format=\"html_v1\">…</section>.\n"
    "- Холст слайда 1200×675px (16:9). Весь контент обязан помещаться: высота"
    " ≤675px, поля ≤64px, отступ от краёв ≥24px. Не помещается — сократите текст.\n"
    "- Правый верхний и правый нижний углы зарезервированы: приложение само"
    " рисует там вотермарк и счётчик слайдов. НЕ размещайте в этих углах свой"
    " контент (лейблы, логотипы, эйброу, подписи) — оставляйте их свободными.\n"
    "- Внутри — любой HTML/CSS/SVG, инлайн-стили разрешены. ЗАПРЕЩЕНО: <script>,"
    " <style>, <iframe>, <object>, <embed>, <form>, <input>, <link>, <meta>,"
    " on*-обработчики, javascript:/vbscript:/file: URL.\n"
    "- Изображения — <img src=\"cid:primary\"> или data:image-URL.\n"
    "- Числовые данные дублируйте в metadata.chart (bar|column|line|area|pie|"
    "doughnut|radar) — для экспорта в PPTX.\n"
    "- Ответ — РОВНО один JSON-объект, без markdown, код-фенсов и текста вне JSON."
)


